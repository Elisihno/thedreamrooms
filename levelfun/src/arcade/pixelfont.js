const rows = {};
for (const k in G) rows[k] = G[k].split(' ');

export function textWidth(text, scale = 1) { return text.length * 6 * scale - scale; }

// Draws text with its top-left corner at (x, y); each font pixel is `scale` canvas pixels.
export function drawText(ctx, text, x, y, scale = 1, color = '#fff', shadow = null) {
  const draw = (ox, oy, col) => {
    ctx.fillStyle = col;
    let cx = x + ox;
    for (const ch of text.toUpperCase()) {
      const g = rows[ch] || rows['?'];
      for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (g[r][c] === '1') ctx.fillRect(cx + c * scale, y + oy + r * scale, scale, scale);
      cx += 6 * scale;
    }
  };
  if (shadow) draw(scale, scale, shadow);
  draw(0, 0, color);
}

export function drawCentered(ctx, text, cx, y, scale, color, shadow) { drawText(ctx, text, Math.round(cx - textWidth(text, scale) / 2), y, scale, color, shadow); }
